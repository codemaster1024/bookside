/** 叙事类、还没读完时的防剧透要求；不需要时为空串。 */
export function spoilerRule(mode: ReadingMode, position: string | undefined): string {
  if (mode !== "narrative" || !position) return "";
  return `\n\n读者还没读完（${position}）。只写到读者读到的位置为止：后面的情节、人物的命运、结局与关键转折一律不写，也不暗示。`;
}
